"""
layer2_5/web_crawler.py — JavaScript-aware deep crawling via Katana.

Katana (ProjectDiscovery) is a fast, headless JS crawler that executes
JavaScript and extracts all URLs, API endpoints, form actions, and asset
references — including those dynamically generated by React/Angular/Vue apps.

Active mode only — crawling generates significant request volume visible in
target's access logs. Routes via VPS when active_recon_via_vps is set.

CLI tool required: katana (from ProjectDiscovery).
Chromium or Firefox required for headless mode (-headless flag).
"""
from __future__ import annotations

import json
import time
from typing import Any

import structlog

from core.config import Config
from core.network import run_command
from core.prefilter import extract_signals
from core.scope_guard import filter_in_scope
from scope_parser import Scope

log = structlog.get_logger(__name__)

MODULE_META = {
    "name":     "web_crawler",
    "title":    "Web Crawler",
    "description": "JavaScript-aware deep crawl for endpoints",
    "layer":    2.5,
    "mode":     ["active"],
    "requires": [],
    "optional": True,
}


async def run(scope: Scope, config: Config, db: Any) -> dict:
    t0        = time.monotonic()
    findings: list[dict] = []
    metadata: dict       = {"domains_crawled": 0, "urls_found": 0}

    hosts = await _get_hosts(scope, db)

    for host in hosts[:20]:  # cap crawl targets
        url       = f"https://{host}"
        crawl_results = await _run_katana(url, config)
        metadata["domains_crawled"] += 1
        metadata["urls_found"]      += len(crawl_results)

        for entry in crawl_results:
            endpoint  = entry.get("request", {}).get("endpoint", "")
            method    = entry.get("request", {}).get("method", "GET")
            resp_code = entry.get("response", {}).get("status_code")
            body      = entry.get("response", {}).get("body", "")[:500]

            signals = extract_signals(f"{endpoint} {body}")

            findings.append({
                "type":  "crawled_endpoint",
                "value": endpoint,
                "data": {
                    "url":         endpoint,
                    "method":      method,
                    "status_code": resp_code,
                    "host":        host,
                    "signals":     signals.as_dict(),
                    "source":      "katana",
                },
            })

            # Flag interesting endpoints
            if _is_interesting(endpoint):
                findings.append({
                    "type":  "interesting_endpoint",
                    "value": endpoint,
                    "data": {
                        "url":    endpoint,
                        "host":   host,
                        "reason": _classify_endpoint(endpoint),
                    },
                })

    return {
        "module":   "layer2_5/web_crawler",
        "status":   "success" if findings else "partial",
        "findings": findings,
        "metadata": metadata,
        "duration": time.monotonic() - t0,
        "error":    None,
    }


async def _get_hosts(scope: Scope, db: Any) -> list[str]:
    hosts: set[str] = set(scope.all_domains)
    if db is not None:
        try:
            run_id = await db.get_last_run_id(scope.target.name) or ""
            if run_id:
                rows = await db.get_findings(run_id, "resolved_host")
                hosts.update(r["value"] for r in rows if r.get("value"))
        except Exception:
            pass
    # Hosts from the DB are runtime discoveries and may include domains the
    # client never authorised. Never hand an unauthorised host to a tool that
    # sends traffic.
    return sorted(filter_in_scope(hosts, scope, module=__name__))


async def _run_katana(url: str, config: Config) -> list[dict]:
    result = await run_command(
        [
            "katana",
            "-u",      url,
            "-jc",            # JavaScript crawling
            "-headless",      # headless browser mode
            "-silent",
            "-jsonl",
            "-depth",  "3",
            "-rate-limit", "100",
            "-timeout", "10",
        ],
        recon_mode="active",
        config=config,
        timeout=config.timeouts.katana,
    )

    if not result.ok and not result.stdout.strip():
        if "not found" in result.stderr:
            log.warning("katana.not_installed")
        return []

    entries = []
    for line in result.stdout.splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            entries.append(json.loads(line))
        except json.JSONDecodeError:
            # Plain URL output (non-JSON mode fallback)
            if line.startswith("http"):
                entries.append({"request": {"endpoint": line, "method": "GET"}})

    return entries


import re as _re
_INTERESTING_PATTERNS = _re.compile(
    r"/(api|v\d+|graphql|rest|swagger|openapi|admin|debug|actuator|"
    r"metrics|health|status|config|env|internal|private|backup|"
    r"\.git|\.env|\.aws|\.ssh|wp-admin|phpmyadmin|panel|console)/",
    _re.IGNORECASE,
)


def _is_interesting(url: str) -> bool:
    return bool(_INTERESTING_PATTERNS.search(url))


def _classify_endpoint(url: str) -> str:
    url_l = url.lower()
    if "/api" in url_l or "/v1" in url_l or "/v2" in url_l:
        return "api_endpoint"
    if "/graphql" in url_l:
        return "graphql_endpoint"
    if "swagger" in url_l or "openapi" in url_l:
        return "api_documentation"
    if "/admin" in url_l or "/console" in url_l or "/panel" in url_l:
        return "admin_panel"
    if "/actuator" in url_l or "/metrics" in url_l or "/health" in url_l:
        return "monitoring_endpoint"
    if "/.git" in url_l or "/.env" in url_l or "/.aws" in url_l:
        return "exposed_sensitive_file"
    if "/debug" in url_l or "/env" in url_l or "/config" in url_l:
        return "debug_endpoint"
    return "interesting_endpoint"
